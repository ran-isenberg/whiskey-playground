"""AgentCore Observability: start AWS Distro for OpenTelemetry (ADOT) in-process.

The docs run agents under `opentelemetry-instrument python main.py`. With direct code deploy the console
script generated by `pip install --target` carries the build machine's interpreter in its shebang, so we
call the same initializer it would call instead. AgentCore Runtime supplies the exporter settings
(OTLP endpoints, log group headers) as ADOT environment variables; Strands emits GenAI spans on its own.

Gated on OBSERVABILITY_ENABLED (set only on the runtime), so local runs and unit tests export nothing.
"""

import logging
import os

log = logging.getLogger(__name__)


def setup() -> bool:
    if os.environ.get('OBSERVABILITY_ENABLED', 'false').lower() != 'true':
        return False
    if os.environ.get('DISABLE_ADOT_OBSERVABILITY', 'false').lower() == 'true':
        return False
    os.environ.setdefault('OTEL_PYTHON_DISTRO', 'aws_distro')
    os.environ.setdefault('OTEL_PYTHON_CONFIGURATOR', 'aws_configurator')
    try:
        from opentelemetry.instrumentation.auto_instrumentation import initialize

        initialize()
    except Exception:  # noqa: BLE001 - observability must never break the agent
        log.exception('ADOT initialization failed; continuing without tracing')
        return False
    return True
